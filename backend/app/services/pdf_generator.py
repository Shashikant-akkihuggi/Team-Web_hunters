import io
from typing import Dict, Any
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, PageBreak, KeepTogether, HRFlowable
)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch

def generate_handover_pdf(handover_title: str, content: Dict[str, Any]) -> io.BytesIO:
    """
    Renders an enterprise-grade PDF handover document using ReportLab.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40
    )

    styles = getSampleStyleSheet()
    
    # Custom color palette (Navy & Teal enterprise theme)
    navy = colors.HexColor("#0f172a")
    teal = colors.HexColor("#0d9488")
    slate = colors.HexColor("#475569")
    light_bg = colors.HexColor("#f8fafc")
    border_color = colors.HexColor("#e2e8f0")

    # Typography styles
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=22,
        leading=26,
        textColor=navy,
        spaceAfter=6
    )

    subtitle_style = ParagraphStyle(
        'DocSubtitle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=11,
        leading=14,
        textColor=teal,
        spaceAfter=15
    )

    h2_style = ParagraphStyle(
        'SectionH2',
        parent=styles['Heading2'],
        fontName='Helvetica-Bold',
        fontSize=14,
        leading=18,
        textColor=navy,
        spaceBefore=12,
        spaceAfter=6
    )

    body_style = ParagraphStyle(
        'BodyDark',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9.5,
        leading=13,
        textColor=navy,
        spaceAfter=6
    )

    meta_label = ParagraphStyle(
        'MetaLabel',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=8.5,
        textColor=slate
    )

    meta_val = ParagraphStyle(
        'MetaVal',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=8.5,
        textColor=navy
    )

    story = []

    # 1. Header Banner
    story.append(Paragraph("KNOWLEDGE CONTINUITY PLATFORM", subtitle_style))
    story.append(Paragraph(handover_title, title_style))
    
    # Metadata Box
    meta_info = content.get("review_and_approval_info", {})
    meta_data = [
        [
            Paragraph("<b>Target Role:</b>", meta_label),
            Paragraph(str(meta_info.get("target_role", "Incoming Member")), meta_val),
            Paragraph("<b>Generated By:</b>", meta_label),
            Paragraph(str(meta_info.get("generated_by", "Lead Engineer")), meta_val)
        ],
        [
            Paragraph("<b>Project:</b>", meta_label),
            Paragraph(str(meta_info.get("project_name", "Handover")), meta_val),
            Paragraph("<b>Status:</b>", meta_label),
            Paragraph(str(meta_info.get("approval_state", "APPROVED")), meta_val)
        ]
    ]
    meta_table = Table(meta_data, colWidths=[1.1*inch, 2.3*inch, 1.1*inch, 2.3*inch])
    meta_table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,-1), light_bg),
        ('BOX', (0,0), (-1,-1), 1, border_color),
        ('INNERGRID', (0,0), (-1,-1), 0.5, border_color),
        ('TOPPADDING', (0,0), (-1,-1), 5),
        ('BOTTOMPADDING', (0,0), (-1,-1), 5),
        ('LEFTPADDING', (0,0), (-1,-1), 8),
        ('RIGHTPADDING', (0,0), (-1,-1), 8),
    ]))
    story.append(meta_table)
    story.append(Spacer(1, 15))

    # Helper function to append section
    def add_section(num: int, title: str, text: str):
        story.append(Paragraph(f"{num}. {title.upper()}", h2_style))
        story.append(HRFlowable(width="100%", thickness=1, color=teal, spaceBefore=2, spaceAfter=6))
        story.append(Paragraph(text, body_style))
        story.append(Spacer(1, 8))

    # Section 1 & 2
    add_section(1, "Project Overview", content.get("project_overview", "No overview provided."))
    add_section(2, "Current Project Status", content.get("current_status", "No status provided."))

    # Section 3: Completed Work
    story.append(Paragraph("3. COMPLETED WORK", h2_style))
    story.append(HRFlowable(width="100%", thickness=1, color=teal, spaceBefore=2, spaceAfter=6))
    for item in content.get("completed_work", []):
        story.append(Paragraph(f"• <b>{item.get('title', 'Accomplishment')}</b> (Page {item.get('evidence_page', 'N/A')}): {item.get('description', '')}", body_style))
    story.append(Spacer(1, 8))

    # Section 4: Pending Tasks
    story.append(Paragraph("4. PENDING TASKS & DEADLINES", h2_style))
    story.append(HRFlowable(width="100%", thickness=1, color=teal, spaceBefore=2, spaceAfter=6))
    for t in content.get("pending_tasks", []):
        owner_str = f" [Owner: {t.get('owner')}]" if t.get('owner') else ""
        deadline_str = f" [Deadline: {t.get('deadline')}]" if t.get('deadline') else ""
        story.append(Paragraph(f"• <b>{t.get('title', 'Task')}</b>{owner_str}{deadline_str}: {t.get('description', '')}", body_style))
    story.append(Spacer(1, 8))

    # Section 5: Important Decisions
    story.append(Paragraph("5. ARCHITECTURAL & STRATEGIC DECISIONS", h2_style))
    story.append(HRFlowable(width="100%", thickness=1, color=teal, spaceBefore=2, spaceAfter=6))
    for d in content.get("important_decisions", []):
        story.append(Paragraph(f"• <b>{d.get('decision', 'Decision')}</b>: {d.get('context', '')} <i>(Quote: \"{d.get('supporting_quote', '')}\" - Page {d.get('page', '1')})</i>", body_style))
    story.append(Spacer(1, 8))

    # Section 6: Blockers
    story.append(Paragraph("6. ACTIVE BLOCKERS & IMPEDIMENTS", h2_style))
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#dc2626"), spaceBefore=2, spaceAfter=6))
    for b in content.get("blockers", []):
        story.append(Paragraph(f"• <b>[CRITICAL BLOCKER] {b.get('blocker', 'Blocker')}</b>: {b.get('impact', '')} (Page {b.get('page', '1')})", body_style))
    story.append(Spacer(1, 8))

    # Section 7: Risks
    story.append(Paragraph("7. RISK REGISTER", h2_style))
    story.append(HRFlowable(width="100%", thickness=1, color=teal, spaceBefore=2, spaceAfter=6))
    for r in content.get("risks", []):
        story.append(Paragraph(f"• <b>[{r.get('severity', 'MEDIUM')}] {r.get('risk', 'Risk')}</b>: {r.get('details', '')} | <i>Mitigation: {r.get('mitigation', '')}</i>", body_style))
    story.append(Spacer(1, 8))

    # Section 8: Unresolved Questions
    story.append(Paragraph("8. UNRESOLVED QUESTIONS", h2_style))
    story.append(HRFlowable(width="100%", thickness=1, color=teal, spaceBefore=2, spaceAfter=6))
    for q in content.get("unresolved_questions", []):
        story.append(Paragraph(f"• <b>? {q.get('question', 'Question')}</b>: {q.get('context', '')}", body_style))
    story.append(Spacer(1, 8))

    # Section 9: Recommended Next Actions
    story.append(Paragraph("9. RECOMMENDED ONBOARDING ACTIONS", h2_style))
    story.append(HRFlowable(width="100%", thickness=1, color=teal, spaceBefore=2, spaceAfter=6))
    for act in content.get("recommended_next_actions", []):
        story.append(Paragraph(f"• <b>{act.get('timeframe', 'Action')}</b>: {act.get('action', '')}", body_style))
    story.append(Spacer(1, 10))

    # Section 10: Evidence References Table
    story.append(Paragraph("10. EVIDENCE TRACEABILITY AUDIT", h2_style))
    story.append(HRFlowable(width="100%", thickness=1, color=teal, spaceBefore=2, spaceAfter=6))
    
    table_rows = [
        [
            Paragraph("<b>Entity</b>", meta_label),
            Paragraph("<b>Source Document</b>", meta_label),
            Paragraph("<b>Page</b>", meta_label),
            Paragraph("<b>Verified Quotation</b>", meta_label)
        ]
    ]

    for ref in content.get("evidence_references", [])[:15]:
        quote_snippet = (ref.get("quotation", "")[:85] + "...") if len(ref.get("quotation", "")) > 85 else ref.get("quotation", "")
        table_rows.append([
            Paragraph(f"<b>{ref.get('entity_type', 'FACT')}</b>: {ref.get('title', '')[:25]}", meta_val),
            Paragraph(str(ref.get('source_doc', 'Doc'))[:20], meta_val),
            Paragraph(f"p.{ref.get('page_number', 1)}", meta_val),
            Paragraph(f"<i>\"{quote_snippet}\"</i>", meta_val),
        ])

    if len(table_rows) > 1:
        ev_table = Table(table_rows, colWidths=[1.8*inch, 1.4*inch, 0.6*inch, 3.0*inch])
        ev_table.setStyle(TableStyle([
            ('BACKGROUND', (0,0), (-1,0), colors.HexColor("#e2e8f0")),
            ('BOX', (0,0), (-1,-1), 1, border_color),
            ('INNERGRID', (0,0), (-1,-1), 0.5, border_color),
            ('TOPPADDING', (0,0), (-1,-1), 4),
            ('BOTTOMPADDING', (0,0), (-1,-1), 4),
            ('LEFTPADDING', (0,0), (-1,-1), 5),
            ('RIGHTPADDING', (0,0), (-1,-1), 5),
        ]))
        story.append(ev_table)

    doc.build(story)
    buffer.seek(0)
    return buffer
